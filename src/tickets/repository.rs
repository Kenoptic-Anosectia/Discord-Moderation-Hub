//! Durable ticket storage: panel provenance, ticket slots, and the create state machine.
//!
//! This module owns the SQLite side of the ticket feature: it stores which panel message
//! may open tickets, reserves one slot per (guild, opener, kind), and drives the
//! `reserved -> creating -> active|failed` transitions around Discord channel creation.
//! It does NOT create Discord channels, greet users, or auto-adopt a channel it did not
//! attach itself.
//!
//! Trust boundary: every method takes ids and strings that ultimately come from Discord
//! payloads, so they are untrusted. Ids are stored as TEXT and parsed back on read; a
//! parse failure surfaces as an error rather than a silent default. State transitions are
//! compare-and-set: a caller that lost a race gets `false` or an error.

use super::policy::Kind;
use crate::Error;
use rusqlite::{params, OptionalExtension};
use std::sync::Arc;
use tokio_rusqlite::Connection;

/// Handle to the ticket database. Cloning shares the same connection; the connection is
/// owned so the database file outlives the individual `Repository` values.
#[derive(Clone)]
pub struct Repository {
    pub(super) db: Arc<Connection>,
}

/// One ticket row as stored in SQLite.
///
/// `status` is the state-machine state (`reserved`, `creating`, `active`, `failed`, ...);
/// `channel` is `None` until a channel has been created and attached; `greeting` is `pending`
/// until the greeting attempt is recorded; `operation` is the opaque per-ticket marker id.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Ticket {
    /// Monotonic ticket id (row id).
    pub id: i64,
    /// Opaque per-ticket operation id, generated by the database.
    pub operation: String,
    /// Guild the ticket belongs to.
    pub guild: u64,
    /// User the ticket was opened for.
    pub opener: u64,
    /// Ticket kind.
    pub kind: Kind,
    /// Current state-machine state.
    pub status: String,
    /// Discord channel id of the ticket, once one has been attached.
    pub channel: Option<u64>,
    /// Greeting delivery state: `pending`, `sent` or `failed`.
    pub greeting: String,
}

/// Provenance of a published ticket panel: the exact guild/channel/message triple and the bot
/// account that authored it. A button press is only honoured when all four match an active
/// panel row.
#[derive(Clone, Copy, Debug)]
pub struct Panel {
    /// Guild the panel was posted in.
    pub guild: u64,
    /// Channel the panel message lives in.
    pub channel: u64,
    /// Id of the panel message itself.
    pub message: u64,
    /// Id of the bot account that authored the panel message.
    pub bot: u64,
}
impl Repository {
    /// Records a newly published panel as the active panel for its guild.
    ///
    /// Any previously stored panel for the same guild is deactivated first, in the same
    /// transaction, so republishing invalidates the old panel. The stored row is what
    /// `trusted_panel` later checks; a panel that was never saved here is inert.
    pub async fn save_panel(&self, p: Panel) -> Result<(), Error> {
        self.db
            .call(move |c| -> rusqlite::Result<()> {
                // IMMEDIATE so the deactivate+insert pair is atomic against a concurrent
                // publish: there must never be two active panels for one guild.
                let tx = c.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)?;
                tx.execute(
                    "UPDATE ticket_panels SET active=0 WHERE guild=?1",
                    [p.guild.to_string()],
                )?;
                tx.execute(
                    "INSERT INTO ticket_panels(guild,channel,message,bot) VALUES(?1,?2,?3,?4)",
                    params![
                        p.guild.to_string(),
                        p.channel.to_string(),
                        p.message.to_string(),
                        p.bot.to_string()
                    ],
                )?;
                tx.commit()?;
                Ok(())
            })
            .await?;
        Ok(())
    }
    /// True only when all four panel fields match an active stored panel for this guild.
    ///
    /// All of guild, channel, message and bot must match exactly: a copied panel message
    /// carries a different channel or message id and is therefore not trusted.
    pub async fn trusted_panel(&self, p: Panel) -> Result<bool, Error> {
        Ok(self.db.call(move |c| -> rusqlite::Result<bool> { c.query_row("SELECT EXISTS(SELECT 1 FROM ticket_panels WHERE guild=?1 AND channel=?2 AND message=?3 AND bot=?4 AND active=1)",params![p.guild.to_string(),p.channel.to_string(),p.message.to_string(),p.bot.to_string()],|r|r.get(0)) }).await?)
    }
    /// One-shot transition `reserved -> creating`.
    ///
    /// Returns true only for the single caller whose UPDATE matched exactly one row, so
    /// exactly one caller may proceed to create a Discord channel. A false return means the
    /// ticket was already claimed (or is not in `reserved`), and the caller must not create
    /// a channel.
    pub async fn claim(&self, id: i64) -> Result<bool, Error> {
        Ok(self
            .db
            .call(move |c| -> rusqlite::Result<bool> {
                Ok(c.execute(
                    "UPDATE tickets SET status='creating' WHERE id=?1 AND status='reserved'",
                    [id],
                )? == 1)
            })
            .await?)
    }
    /// Transition `creating -> active` and stores the created channel id.
    ///
    /// The update matches on the ticket id and on `status='creating'` only; it does NOT
    /// check that the row has no channel yet, so it will overwrite an already-stored
    /// channel id if one is present. The caller is responsible for calling this exactly
    /// once, after a successful channel creation, on a ticket it has claimed.
    ///
    /// Fails with an error when the update did not change exactly one row, i.e. the ticket
    /// was not in `creating`. The error is deliberately loud because it means the caller
    /// lost a race or is out of order.
    pub async fn attach(&self, id: i64, channel: u64) -> Result<(), Error> {
        self.db.call(move |c| -> rusqlite::Result<()> {
   let changed=c.execute("UPDATE tickets SET status='active',channel=?2 WHERE id=?1 AND status='creating'",params![id,channel.to_string()])?;
   if changed!=1 { return Err(rusqlite::Error::InvalidQuery); } Ok(())
  }).await?;
        Ok(())
    }
    /// Transition `creating -> failed` for a channel creation that was definitively rejected.
    ///
    /// Only legal while no channel is attached (`channel IS NULL`); if the row is not in
    /// `creating` or already has a channel the update changes nothing and the method
    /// returns an error instead of silently overwriting state.
    pub async fn failed(&self, id: i64) -> Result<(), Error> {
        self.db.call(move |c| -> rusqlite::Result<()> { if c.execute("UPDATE tickets SET status='failed' WHERE id=?1 AND status='creating' AND channel IS NULL",[id])?!=1 { return Err(rusqlite::Error::InvalidQuery); } Ok(()) }).await?;
        Ok(())
    }
    /// Records the outcome of the greeting attempt on an `active` ticket.
    ///
    /// `sent` is stored as `sent`, otherwise `failed`. Only rows in `active` are updated; the
    /// number of changed rows is not checked, so a greeting outcome for a ticket that is no
    /// longer active is dropped rather than an error.
    pub async fn greeting_result(&self, id: i64, sent: bool) -> Result<(), Error> {
        self.db
            .call(move |c| -> rusqlite::Result<()> {
                c.execute(
                    "UPDATE tickets SET greeting=?2 WHERE id=?1 AND status='active'",
                    params![id, if sent { "sent" } else { "failed" }],
                )?;
                Ok(())
            })
            .await?;
        Ok(())
    }
    /// Opens (and migrates) the ticket database and returns a repository for it.
    ///
    /// `:memory:` opens an in-memory database, which is what the tests use. Any other path is
    /// created if missing. The schema migration runs before the repository is handed out, so
    /// a caller can rely on the v2 schema and its auxiliary tables existing.
    pub async fn open(path: &str) -> Result<Self, Error> {
        let db = if path == ":memory:" {
            Connection::open_in_memory().await?
        } else {
            Connection::open(path).await?
        };
        db.call(|c| -> rusqlite::Result<()> { super::repository_close::migrate(c) })
            .await?;
        Ok(Self { db: Arc::new(db) })
    }
    /// Reserves (or re-attaches to) the ticket slot for this interaction.
    ///
    /// The lookup order inside one IMMEDIATE transaction is: (1) an interaction id already
    /// bound to a ticket returns that same ticket, which makes a retried button press
    /// idempotent; (2) otherwise the existing non-terminal slot for
    /// (guild, opener, kind) is reused, so one user cannot open a second ticket of the same
    /// kind; (3) otherwise a new `reserved` row is inserted. The interaction binding is
    /// always recorded. The returned ticket is the current row, so the caller must inspect
    /// `status` and `channel` to learn whether it already has a channel.
    ///
    /// `interaction`, `guild` and `opener` are untrusted Discord ids; they are stored and
    /// compared exactly, and no authorisation decision is made here.
    pub async fn reserve(
        &self,
        interaction: u64,
        guild: u64,
        opener: u64,
        kind: Kind,
    ) -> Result<Ticket, Error> {
        Ok(self.db.call(move |c| -> rusqlite::Result<Ticket> {
   let tx=c.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)?;
   let previous:Option<i64>=tx.query_row("SELECT ticket FROM ticket_interactions WHERE interaction=?1",[interaction.to_string()],|r|r.get(0)).optional()?;
   let id=if let Some(id)=previous { id } else {
    let slot:Option<i64>=tx.query_row("SELECT id FROM tickets WHERE guild=?1 AND opener=?2 AND kind=?3 AND status IN ('reserved','creating','active','closing','archiving','verified','delete_requested','delete_uncertain','recovery')",params![guild.to_string(),opener.to_string(),kind.key()],|r|r.get(0)).optional()?;
    let id=if let Some(id)=slot { id } else {
     tx.execute("INSERT INTO tickets(guild,opener,kind,status) VALUES(?1,?2,?3,'reserved')",params![guild.to_string(),opener.to_string(),kind.key()])?;
     tx.last_insert_rowid()
    };
    tx.execute("INSERT INTO ticket_interactions(interaction,ticket) VALUES(?1,?2)",params![interaction.to_string(),id])?; id
   };
   let ticket=tx.query_row("SELECT id,guild,opener,kind,status,channel,greeting,operation FROM tickets WHERE id=?1",[id],read_ticket)?;
   tx.commit()?; Ok(ticket)
  }).await?)
    }
}
/// Reads one ticket row into a `Ticket`.
///
/// Column order must match the `COLS` select list used by the other queries:
/// id, guild, opener, kind, status, channel, greeting, operation. Snowflake ids are stored as
/// TEXT and parsed here; a value that is not a number is reported as a conversion error
/// instead of being coerced. An unknown `kind` value is read as `Kind::Support`, matching the
/// schema's two-value CHECK constraint.
pub(super) fn read_ticket(r: &rusqlite::Row<'_>) -> rusqlite::Result<Ticket> {
    fn snowflake(r: &rusqlite::Row<'_>, i: usize) -> rusqlite::Result<u64> {
        let s: String = r.get(i)?;
        s.parse().map_err(|e| {
            rusqlite::Error::FromSqlConversionFailure(i, rusqlite::types::Type::Text, Box::new(e))
        })
    }
    let channel: Option<String> = r.get(5)?;
    let channel = channel.map(|s| s.parse::<u64>()).transpose().map_err(|e| {
        rusqlite::Error::FromSqlConversionFailure(5, rusqlite::types::Type::Text, Box::new(e))
    })?;
    Ok(Ticket {
        id: r.get(0)?,
        operation: r.get(7)?,
        guild: snowflake(r, 1)?,
        opener: snowflake(r, 2)?,
        kind: if r.get::<_, String>(3)? == "age" {
            Kind::Age
        } else {
            Kind::Support
        },
        status: r.get(4)?,
        channel,
        greeting: r.get(6)?,
    })
}
#[cfg(test)]
#[path = "repository_tests.rs"]
pub(crate) mod a07_tests;
#[cfg(test)]
mod tests {
    use super::*;
    /// Proves the slot and the opaque operation survive separate connections and a restart.
    /// Fails if slot reuse, the one-shot claim or the operation column stops persisting.
    #[tokio::test]
    async fn separate_connections_and_restart_preserve_slots_and_opaque_operations() {
        static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("target-a06-candidate/owned-db-tests");
        std::fs::create_dir_all(&root).unwrap();
        let path = root.join(format!(
            "{}-{}-{}.sqlite",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos(),
            NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
        ));
        let path = path.to_str().unwrap();
        let a = Repository::open(path).await.unwrap();
        let b = Repository::open(path).await.unwrap();
        let (x, y) = tokio::join!(
            a.reserve(1, 100, u64::MAX, Kind::Support),
            b.reserve(2, 100, u64::MAX, Kind::Support)
        );
        let x = x.unwrap();
        assert_eq!(x.id, y.unwrap().id);
        assert_eq!(x.operation.len(), 32);
        assert!(x.operation.chars().all(|c| c.is_ascii_hexdigit()));
        let (one, two) = tokio::join!(a.claim(x.id), b.claim(x.id));
        assert_ne!(one.unwrap(), two.unwrap());
        let z = b.reserve(3, 100, 999, Kind::Age).await.unwrap();
        assert_ne!(z.operation, x.operation);
        b.claim(z.id).await.unwrap();
        b.attach(z.id, u64::MAX).await.unwrap();
        drop(a);
        drop(b);
        let reopened = Repository::open(path).await.unwrap();
        let x2 = reopened
            .reserve(1, 100, u64::MAX, Kind::Support)
            .await
            .unwrap();
        assert_eq!(x2.status, "creating");
        assert_eq!(x2.operation, x.operation);
        let z2 = reopened.reserve(3, 100, 999, Kind::Age).await.unwrap();
        assert_eq!(z2.status, "active");
        assert_eq!(z2.channel, Some(u64::MAX));
        assert_eq!(z2.greeting, "pending");
        assert!(
            reopened
                .reserve(4, 100, 1000, Kind::Support)
                .await
                .unwrap()
                .id
                > z.id
        );
    }
    /// Proves panel trust is exact on all four fields and that republishing deactivates the
    /// previous panel. Fails if a field stops being compared, or the old panel stays trusted.
    #[tokio::test]
    async fn panel_provenance_is_exact() {
        let r = Repository::open(":memory:").await.unwrap();
        let p = Panel {
            guild: 100,
            channel: 200,
            message: u64::MAX,
            bot: 400,
        };
        r.save_panel(p).await.unwrap();
        assert!(r.trusted_panel(p).await.unwrap());
        for altered in [
            Panel { guild: 101, ..p },
            Panel { channel: 201, ..p },
            Panel { message: 1, ..p },
            Panel { bot: 401, ..p },
        ] {
            assert!(!r.trusted_panel(altered).await.unwrap());
        }
        let replacement = Panel { message: 42, ..p };
        r.save_panel(replacement).await.unwrap();
        assert!(
            !r.trusted_panel(p).await.unwrap(),
            "republished panel makes the old panel stale"
        );
        assert!(r.trusted_panel(replacement).await.unwrap());
    }
    /// Proves the create state machine is a compare-and-set: one concurrent claim wins and
    /// a failed slot is released. Fails if a transition becomes unconditional.
    #[tokio::test]
    async fn claim_attach_and_known_failure_are_durable_and_concurrent() {
        let r = Repository::open(":memory:").await.unwrap();
        let (a, b) = tokio::join!(
            r.reserve(1, 100, 2, Kind::Support),
            r.reserve(2, 100, 2, Kind::Support)
        );
        let a = a.unwrap();
        assert_eq!(a.id, b.unwrap().id);
        let (a1, a2) = tokio::join!(r.claim(a.id), r.claim(a.id));
        assert_ne!(a1.unwrap(), a2.unwrap());
        assert_eq!(
            r.reserve(3, 100, 2, Kind::Support).await.unwrap().status,
            "creating"
        );
        r.attach(a.id, u64::MAX).await.unwrap();
        r.greeting_result(a.id, false).await.unwrap();
        let active = r.reserve(1, 100, 2, Kind::Support).await.unwrap();
        assert_eq!(active.channel, Some(u64::MAX));
        assert_eq!(active.greeting, "failed");
        assert_eq!(active.status, "active");
        assert!(r.failed(a.id).await.is_err());
        let b = r.reserve(4, 100, 3, Kind::Support).await.unwrap();
        assert!(r.claim(b.id).await.unwrap());
        r.failed(b.id).await.unwrap();
        assert_eq!(
            r.reserve(4, 100, 3, Kind::Support).await.unwrap().status,
            "failed"
        );
        assert!(r.reserve(5, 100, 3, Kind::Support).await.unwrap().id > b.id);
    }
    /// Proves reservation is idempotent per interaction id and that the slot is per
    /// (opener, kind). Fails if reservation stops being idempotent or slots collide.
    #[tokio::test]
    async fn reservation_is_idempotent_and_slots_are_per_type_and_user() {
        let r = Repository::open(":memory:").await.unwrap();
        let a = r
            .reserve(u64::MAX, 100, u64::MAX, Kind::Support)
            .await
            .unwrap();
        assert_eq!(
            a,
            r.reserve(u64::MAX, 100, u64::MAX, Kind::Support)
                .await
                .unwrap()
        );
        assert_eq!(
            a.id,
            r.reserve(2, 100, u64::MAX, Kind::Support).await.unwrap().id
        );
        let b = r.reserve(3, 100, u64::MAX, Kind::Age).await.unwrap();
        let c = r.reserve(4, 100, 5, Kind::Support).await.unwrap();
        assert!(a.id < b.id && b.id < c.id);
        assert_eq!(a.opener, u64::MAX);
        assert_eq!(a.status, "reserved");
    }
}
